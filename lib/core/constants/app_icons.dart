  /// Maps a backend category slug / name to an icon.
  static IconData forCategory(String slug) {
    final s = slug.toLowerCase();
    if (s.contains('dining') || s.contains('food')) return dining;
    if (s.contains('flight')) return flights;
    if (s.contains('fuel')) return fuel;
    if (s.contains('grocery')) return grocery;
    if (s.contains('shopping') || s.contains('online')) return shopping;
    if (s.contains('rent')) return rent;
    if (s.contains('travel') || s.contains('hotel')) return travel;
    if (s.contains('utilit') || s.contains('bill')) return utilities;
    if (s.contains('entertain') || s.contains('movie')) return entertainment;
    if (s.contains('medical') || s.contains('health')) return medical;
    if (s.contains('education')) return education;
    if (s.contains('international') || s.contains('forex')) return international;
    if (s.contains('insurance')) return insurance;
    if (s.contains('government') || s.contains('tax')) return government;
    if (s.contains('upi')) return upi;
    if (s.contains('gift')) return giftCards;
    return general;
  }

  /// Maps a backend Material `icon_key` onto the Lucide set used by the app.
  static IconData fromMaterial(String? key) {
    switch (key) {
      case 'restaurant' || 'dining' || 'local_dining':
        return dining;
      case 'flight' || 'flight_takeoff' || 'airplanemode_active':
        return flights;
      case 'local_gas_station' || 'local_gas_station_outlined':
        return fuel;
      case 'shopping_cart' || 'local_grocery_store':
        return grocery;
      case 'shopping_bag' || 'shopping_bag_outlined':
        return shopping;
      case 'home' || 'house':
        return rent;
      case 'luggage' || 'card_travel' || 'travel_explore':
        return travel;
      case 'bolt' || 'flash_on' || 'receipt_long':
        return utilities;
      case 'movie' || 'theaters' || 'live_tv':
        return entertainment;
      case 'local_hospital' || 'medical_services':
        return medical;
      case 'school':
        return education;
      case 'public' || 'language' || 'language_outlined':
        return international;
      case 'account_balance' || 'assured_workload':
        return government;
      case 'payments' || 'currency_rupee' || 'account_balance_wallet':
        return upi;
      case 'card_giftcard' || 'redeem':
        return gift;
      case 'store' || 'storefront':
        return general;
      case 'auto_awesome' || 'tips_and_updates':
        return navHome;
      case 'credit_card' || 'wallet' || 'account_balance_wallet_outlined':
        return card;
      case 'calculate' || 'pie_chart':
        return navRewards;
      case 'compare_arrows' || 'balance':
        return compare;
      case 'bookmark' || 'bookmark_border':
        return bookmark;
      case 'savings':
        return piggyBank;
      default:
        return key == null || key.isEmpty ? general : forCategory(key);
    }
  }
